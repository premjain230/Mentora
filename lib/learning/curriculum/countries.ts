export const COUNTRY_BY_CODE = new Map(COUNTRIES.map((c) => [c.code, c]));
export const COUNTRY_BY_SLUG = new Map(COUNTRIES.map((c) => [c.slug, c]));

export function getCountry(codeOrSlug: string): Country | undefined {
  if (!codeOrSlug) return undefined;
  const upper = codeOrSlug.toUpperCase();
  if (COUNTRY_BY_CODE.has(upper)) return COUNTRY_BY_CODE.get(upper);
  const lower = codeOrSlug.toLowerCase();
  return COUNTRY_BY_SLUG.get(lower);
}
